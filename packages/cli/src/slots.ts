/**
 * Generates MoonBit slot constants from a behavior's declaration in
 * moonstage.json, so behaviors refer to `param_speed` instead of a bare index
 * that can silently drift from the manifest order.
 *
 * Each MoonBit behavior package gets a `slots.generated.mbt`. `moonstage build`
 * (and therefore run/test/render) rewrites it; `moonstage validate` warns when
 * it is stale. The file is meant to be committed so editors and `moon check`
 * work before the first build.
 */

import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { diagnostic, type BehaviorModuleDecl, type Diagnostic, type ProjectManifest } from "@moonstage/core";

export const SLOTS_FILE = "slots.generated.mbt";

const KINDS = [
  ["params", "param"],
  ["state", "state"],
  ["refs", "ref"],
  ["inputs", "input"],
  ["events", "event"],
  ["prefabs", "prefab"],
  ["scenes", "scene"],
  ["sounds", "sound"],
  ["saves", "save"],
  ["tags", "tag"],
] as const;

/** "turnSpeed" -> "turn_speed", "min-x" -> "min_x", "HP" -> "hp". */
export function snakeCase(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .replace(/-/g, "_")
    .toLowerCase();
}

export function slotsSource(name: string, decl: BehaviorModuleDecl): string {
  const blocks: string[] = [];
  for (const [list, prefix] of KINDS) {
    (decl[list] ?? []).forEach((entry, index) => {
      blocks.push(`///|\n/// ${prefix} "${entry}"\npub let ${prefix}_${snakeCase(entry)} : Int32 = ${index}\n`);
    });
  }
  const header =
    `// Generated by \`moonstage build\` from the "${name}" behavior in moonstage.json.\n` +
    "// Do not edit: change the behavior's params/state/refs/inputs/events/prefabs/scenes/sounds/saves/tags lists instead.\n";
  return blocks.length === 0 ? header : `${header}\n${blocks.join("\n")}`;
}

function sourceBehaviors(manifest: ProjectManifest): [string, BehaviorModuleDecl & { source: string }][] {
  return Object.entries(manifest.behaviors ?? {}).filter(
    (e): e is [string, BehaviorModuleDecl & { source: string }] => e[1].source !== undefined,
  );
}

/** Report generated names that collide after snake-casing (e.g. "minX" and "min_x"). */
export function slotCollisions(manifest: ProjectManifest): Diagnostic[] {
  const out: Diagnostic[] = [];
  for (const [name, decl] of sourceBehaviors(manifest)) {
    for (const [list, prefix] of KINDS) {
      const seen = new Map<string, string>();
      for (const entry of decl[list] ?? []) {
        const id = snakeCase(entry);
        const other = seen.get(id);
        if (other !== undefined) {
          out.push(
            diagnostic("MS2013", `behaviors.${name}.${list}: "${other}" and "${entry}" both become ${prefix}_${id}`, {
              file: "moonstage.json",
              path: `behaviors.${name}.${list}`,
            }),
          );
        }
        seen.set(id, entry);
      }
    }
  }
  return out;
}

async function current(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8");
  } catch {
    return undefined;
  }
}

/** Write slot files that are missing or stale. Returns the project-relative paths written. */
export async function writeSlotFiles(root: string, manifest: ProjectManifest): Promise<string[]> {
  const written: string[] = [];
  for (const [name, decl] of sourceBehaviors(manifest)) {
    const path = join(resolve(root, decl.source), SLOTS_FILE);
    const text = slotsSource(name, decl);
    if ((await current(path)) === text) continue;
    try {
      await writeFile(path, text);
      written.push(`${decl.source}/${SLOTS_FILE}`);
    } catch {
      // Missing source directory: reported by the MoonBit build step.
    }
  }
  return written;
}

/** Warnings for slot files that are missing or out of date. */
export async function staleSlotFiles(root: string, manifest: ProjectManifest): Promise<Diagnostic[]> {
  const out: Diagnostic[] = [];
  for (const [name, decl] of sourceBehaviors(manifest)) {
    const file = `${decl.source}/${SLOTS_FILE}`;
    if ((await current(join(root, file))) !== slotsSource(name, decl)) {
      out.push(diagnostic("MS3008", `generated slots for behavior "${name}" are missing or out of date`, { file, severity: "warning" }));
    }
  }
  return out;
}
