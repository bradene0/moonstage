/** 2D affine matrix [a, b, c, d, e, f], same convention as Canvas 2D and SVG. */
export type Matrix = [number, number, number, number, number, number];

export const IDENTITY: Matrix = [1, 0, 0, 1, 0, 0];

export function multiply(m: Matrix, n: Matrix): Matrix {
  return [
    m[0] * n[0] + m[2] * n[1],
    m[1] * n[0] + m[3] * n[1],
    m[0] * n[2] + m[2] * n[3],
    m[1] * n[2] + m[3] * n[3],
    m[0] * n[4] + m[2] * n[5] + m[4],
    m[1] * n[4] + m[3] * n[5] + m[5],
  ];
}

/** translate(x, y) * rotate(rotation) * scale(sx, sy) */
export function compose(x: number, y: number, rotation: number, sx: number, sy: number): Matrix {
  const cos = Math.cos(rotation);
  const sin = Math.sin(rotation);
  return [cos * sx, sin * sx, -sin * sy, cos * sy, x, y];
}

export function apply(m: Matrix, x: number, y: number): [number, number] {
  return [m[0] * x + m[2] * y + m[4], m[1] * x + m[3] * y + m[5]];
}

/** Inverse of an affine matrix (identity when it is singular). */
export function invert(m: Matrix): Matrix {
  const [a, b, c, d, e, f] = m;
  const det = a * d - b * c;
  if (det === 0) return [1, 0, 0, 1, 0, 0];
  return [d / det, -b / det, -c / det, a / det, (c * f - d * e) / det, (b * e - a * f) / det];
}

export function lerp(a: number, b: number, t: number): number {
  return a + (b - a) * t;
}
